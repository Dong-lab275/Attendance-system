CREATE TABLE studentclasses (
    class_id CHAR(5) PRIMARY KEY,
    class_name VARCHAR(100) NOT NULL,
    academic_year VARCHAR(20) NOT NULL
);

CREATE TABLE users (
    user_id CHAR(12) PRIMARY KEY,
    username VARCHAR(100) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL,
    email VARCHAR(100) NOT NULL UNIQUE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_user_role
    CHECK (role IN ('Administrator', 'Student', 'Lecturer'))
);

CREATE TABLE passwordresetrequests (
    reset_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    user_id CHAR(12) NOT NULL,

    CONSTRAINT fk_passwordreset_user
    FOREIGN KEY (user_id)
    REFERENCES users(user_id)
);

CREATE TABLE departments (
    department_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_name VARCHAR(100) NOT NULL
);

CREATE TABLE students (
    student_id CHAR(12) PRIMARY KEY,
    address VARCHAR(100),
    full_name VARCHAR(100) NOT NULL,
    date_of_birth DATE,
    gender VARCHAR(10),
    phone VARCHAR(15),
    email VARCHAR(100),

    class_id CHAR(5) NOT NULL,
    user_id CHAR(12) NOT NULL UNIQUE,

    CONSTRAINT fk_students_class
    FOREIGN KEY (class_id)
    REFERENCES studentclasses(class_id),

    CONSTRAINT fk_students_user
    FOREIGN KEY (user_id)
    REFERENCES users(user_id)
);

CREATE TABLE lecturers (
    lecturer_id CHAR(12) PRIMARY KEY,
    phone VARCHAR(15),
    full_name VARCHAR(100) NOT NULL,
    email VARCHAR(100),
    date_of_birth DATE,
    gender VARCHAR(10),

    department_id INTEGER NOT NULL,
    user_id CHAR(12) NOT NULL UNIQUE,

    CONSTRAINT fk_lecturers_department
    FOREIGN KEY (department_id)
    REFERENCES departments(department_id),

    CONSTRAINT fk_lecturers_user
    FOREIGN KEY (user_id)
    REFERENCES users(user_id)
);

CREATE TABLE courses (
    course_id CHAR(5) PRIMARY KEY,
    course_code VARCHAR(20) NOT NULL,
    course_name VARCHAR(100) NOT NULL,
    description TEXT,
    credits INTEGER NOT NULL,
    academic_year VARCHAR(20) NOT NULL,
    semester INTEGER NOT NULL,

    lecturer_id CHAR(12) NOT NULL,

    CONSTRAINT fk_courses_lecturer
    FOREIGN KEY (lecturer_id)
    REFERENCES lecturers(lecturer_id)
);

CREATE TABLE courseregistrations (
    registration_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registration_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    registration_status VARCHAR(20) NOT NULL,

    student_id CHAR(12) NOT NULL,
    course_id CHAR(5) NOT NULL,

    CONSTRAINT fk_registration_student
    FOREIGN KEY (student_id)
    REFERENCES students(student_id),

    CONSTRAINT fk_registration_course
    FOREIGN KEY (course_id)
    REFERENCES courses(course_id),

    CONSTRAINT uq_student_course
    UNIQUE (student_id, course_id)
);

CREATE TABLE classsessions (
    session_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class_date DATE NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    classroom VARCHAR(50) NOT NULL,

    course_id CHAR(5) NOT NULL,

    CONSTRAINT fk_sessions_course
    FOREIGN KEY (course_id)
    REFERENCES courses(course_id),

    CONSTRAINT chk_session_time
    CHECK (end_time > start_time)
);

CREATE TABLE attendancerecords (
    attendance_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attendance_timestamp TIMESTAMP,
    status VARCHAR(20) NOT NULL,
    notes TEXT,

    student_id CHAR(12) NOT NULL,
    session_id INTEGER NOT NULL,

    CONSTRAINT fk_attendance_student
    FOREIGN KEY (student_id)
    REFERENCES students(student_id),

    CONSTRAINT fk_attendance_session
    FOREIGN KEY (session_id)
    REFERENCES classsessions(session_id),

    CONSTRAINT uq_student_session
    UNIQUE (student_id, session_id),

    CONSTRAINT chk_attendance_status
    CHECK (status IN ('Present', 'Absent', 'Late'))
);

CREATE TABLE attendancechangehistory (
    history_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    old_status VARCHAR(20),
    new_status VARCHAR(20) NOT NULL,
    modification_timestamp TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reason TEXT,

    user_id CHAR(12) NOT NULL,
    attendance_id INTEGER NOT NULL,

    CONSTRAINT fk_history_user
    FOREIGN KEY (user_id)
    REFERENCES users(user_id),

    CONSTRAINT fk_history_attendance
    FOREIGN KEY (attendance_id)
    REFERENCES attendancerecords(attendance_id)
);


